const contracts = Object.values(TOKEN_CONTRACTS);

async function tvl(api) {
  let results = await api.multiCall({
    abi: "erc20:totalSupply",
    calls: contracts,
  });

  results = results.map((x) => BigInt(x));

  api.addTokens(contracts, results);
}

